"""
Real-world text-to-multi-view inference.

View 0 is generated by Self-Forcing (arbitrary length, rolling KV cache); each
subsequent view is generated by the MV-Forcing student, conditioned on the
previous view and on the CUT3R geometric prior rendered from the accumulated
4D state.

Usage:
    python inference_real_world.py \
        --config_path      configs/inference_real_world.yaml \
        --checkpoint_path  weights/mv_forcing_real_world.pt \
        --sf_checkpoint_path checkpoints/self_forcing_dmd.pt \
        --prompt           "A child dances in a restaurant" \
        --cam_type         az \
        --num_views        3 \
        --total_frames     42 \
        --accumulate_views --local_attn_size 21 --sink_size 12 \
        --output_folder    ./results
"""

import argparse
import json
import os

import numpy as np
import torch
import torch.distributed as dist
from PIL import Image
from diffusers.utils import export_to_video
from einops import rearrange
from omegaconf import OmegaConf
from tqdm import tqdm

from pipeline.text_to_mv_pipeline import TextToMVPipeline
from utils.dataset_mixkit_lmdb import Camera
from utils.memory import gpu, get_cuda_free_memory_gb, DynamicSwapInstaller
from utils.misc import set_seed
from utils.paths import load_cut3r, set_wan_root

# Camera pairs of the SynCamMaster rig used for the three configurations,
# as (conditioning view, target view).
CAM_TYPE_PAIRS = {
    "az": (3, 1),    # 30 degree azimuthal rotation
    "el": (7, 3),    # 20 degree elevation change
    "dis": (10, 9),  # 100 unit dolly, orientation fixed
}


def save_views(video, num_views, output_folder, method_name, prompt_idx,
               prompt_text="", camera_config=None, fps=16):
    prompt_dir = os.path.join(output_folder, method_name, f"prompt_{prompt_idx:04d}")
    os.makedirs(prompt_dir, exist_ok=True)

    for v in range(num_views):
        view_dir = os.path.join(prompt_dir, f"view_{v}")
        frames_dir = os.path.join(view_dir, "frames")
        os.makedirs(frames_dir, exist_ok=True)

        view_vid = video[v]
        for t in range(view_vid.shape[0]):
            frame_np = (view_vid[t].permute(1, 2, 0).cpu().numpy() * 255).astype(np.uint8)
            Image.fromarray(frame_np).save(os.path.join(frames_dir, f"{t:06d}.png"))

        vid_np = view_vid.permute(0, 2, 3, 1).cpu().numpy()
        export_to_video(vid_np, os.path.join(view_dir, "video.mp4"), fps=fps)

    merged = torch.cat([video[v] for v in range(num_views)], dim=3)
    merged_np = merged.permute(0, 2, 3, 1).cpu().numpy()
    export_to_video(merged_np, os.path.join(prompt_dir, "merged.mp4"), fps=fps)

    meta = {
        "prompt": prompt_text,
        "method": method_name,
        "num_views": num_views,
        "num_pixel_frames": int(video.shape[1]),
        "camera_config": camera_config,
    }
    with open(os.path.join(prompt_dir, "metadata.json"), "w") as f:
        json.dump(meta, f, indent=2)

def parse_matrix(matrix_str):
    rows = matrix_str.strip().split('] [')
    matrix = []
    for row in rows:
        row = row.replace('[', '').replace(']', '')
        matrix.append(list(map(float, row.split())))
    return np.array(matrix)

def build_camera_chain(camera_json_path, cam_indices):
    with open(camera_json_path, 'r') as f:
        cam_data = json.load(f)

    cam_frame_indices = list(range(81))[::4]

    def load_trajectory(view_idx):
        traj = [parse_matrix(cam_data[f"frame{idx}"][f"cam{view_idx:02d}"])
                for idx in cam_frame_indices]
        traj = np.stack(traj).transpose(0, 2, 1)
        c2ws = []
        for c2w in traj:
            c2w = c2w[:, [1, 2, 0, 3]]
            c2w[:3, 1] *= -1.
            c2w[:3, 3] /= 200
            c2ws.append(c2w)
        return c2ws

    trajectories = {}
    for idx in set(cam_indices):
        trajectories[idx] = load_trajectory(idx)

    camera_embeddings_list = []
    c2w_matrices = []

    for i in range(len(cam_indices) - 1):
        cond_c2ws = trajectories[cam_indices[i]]
        tgt_c2ws = trajectories[cam_indices[i + 1]]

        cond_cams = [Camera(c) for c in cond_c2ws]
        tgt_cams = [Camera(c) for c in tgt_c2ws]

        relative_poses = []
        for f in range(len(cond_cams)):
            target_cam_c2w = np.eye(4, dtype=np.float32)
            abs2rel = target_cam_c2w @ cond_cams[f].w2c_mat
            ret_poses = [target_cam_c2w, abs2rel @ tgt_cams[f].c2w_mat]
            relative_poses.append(
                torch.as_tensor(np.array(ret_poses, dtype=np.float32))[:, :3, :])

        pose_embedding = torch.stack(relative_poses, dim=1)
        camera_embedding = rearrange(
            pose_embedding, 'v f c d -> v f (c d)').to(torch.bfloat16)

        c2w_cond = torch.tensor(np.stack(cond_c2ws), dtype=torch.float32)
        c2w_tgt = torch.tensor(np.stack(tgt_c2ws), dtype=torch.float32)

        camera_embeddings_list.append(camera_embedding)
        c2w_matrices.append((c2w_cond, c2w_tgt))

    return camera_embeddings_list, c2w_matrices

# ── Args ──────────────────────────────────────────────────────────────────

parser = argparse.ArgumentParser()
parser.add_argument("--config_path", type=str, default="configs/inference_real_world.yaml")
parser.add_argument("--checkpoint_path", type=str, required=True,
                    help="MV-Forcing student checkpoint")
parser.add_argument("--sf_checkpoint_path", type=str,
                    default="checkpoints/self_forcing_dmd.pt",
                    help="Self-Forcing checkpoint, used to generate view 0")
parser.add_argument("--output_folder", type=str, required=True)

# Prompts
parser.add_argument("--prompt", type=str, action="append", default=None,
                    help="Text prompt; repeat the flag for several prompts")
parser.add_argument("--prompt_file", type=str, default=None,
                    help="File with one prompt per line")

# Cameras
parser.add_argument("--camera_json_path", type=str,
                    default="SynCamMaster/example_test_data/cameras/camera_extrinsics.json",
                    help="SynCamMaster camera rig JSON")
parser.add_argument("--cam_type", type=str, default="az", choices=sorted(CAM_TYPE_PAIRS),
                    help="Camera configuration; the same relative transform is "
                         "applied at each view step")
parser.add_argument("--cam_indices", type=int, nargs="+", default=None,
                    help="Explicit camera chain overriding --cam_type, e.g. 3 1 7 "
                         "(cam03 -> cam01 -> cam07); requires --num_views entries")

# Generation
parser.add_argument("--num_views", type=int, default=2)
parser.add_argument("--total_frames", type=int, default=21,
                    help="Latent frames per view (21 latent = 81 pixel frames)")
parser.add_argument("--v0_mode", type=str, default="sf", choices=["sf", "student"],
                    help="View 0 from Self-Forcing ('sf') or from the student's "
                         "joint denoising path ('student')")
parser.add_argument("--accumulate_views", action="store_true",
                    help="Feed all previous views into the CUT3R state, not just the last")
parser.add_argument("--local_attn_size", type=int, default=-1)
parser.add_argument("--sink_size", type=int, default=0)
parser.add_argument("--long_rolling", action="store_true",
                    help="Memory-efficient rolling generation for very long sequences")
parser.add_argument("--fps", type=int, default=16)
parser.add_argument("--seed", type=int, default=24)
parser.add_argument("--method_name", type=str, default=None)

# External assets
parser.add_argument("--wan_root", type=str, default=None,
                    help="Directory holding Wan2.1-T2V-1.3B (defaults to ./wan_models)")
parser.add_argument("--cut3r_root", type=str, default=None,
                    help="CUT3R checkout (defaults to ./CUT3R)")
parser.add_argument("--cut3r_path", type=str,
                    default="CUT3R/src/cut3r_512_dpt_4_64.pth",
                    help="CUT3R checkpoint")

parser.add_argument("--negative_prompt", type=str,
                    default="色调艳丽，过曝，静态，细节模糊不清，字幕，风格，作品，画作，画面，静止，整体发灰，最差质量，低质量，JPEG压缩残留，丑陋的，残缺的，多余的手指，画得不好的手部，画得不好的脸部，畸形的，毁容的，形态畸形的肢体，手指融合，静止不动的画面，杂乱的背景，三条腿，背景人很多，倒着走")

args = parser.parse_args()
set_wan_root(args.wan_root)

if args.method_name is None:
    args.method_name = f"real_world_{args.v0_mode}"

# ── Prompts ───────────────────────────────────────────────────────────────

prompts = list(args.prompt or [])
if args.prompt_file is not None:
    with open(args.prompt_file) as f:
        prompts += [line.strip() for line in f if line.strip()]
if not prompts:
    parser.error("give at least one prompt via --prompt or --prompt_file")

# ── Cameras ───────────────────────────────────────────────────────────────

if args.cam_indices is not None:
    if len(args.cam_indices) != args.num_views:
        parser.error(f"--cam_indices needs exactly --num_views ({args.num_views}) entries")
    cam_indices = args.cam_indices
else:
    cond_idx, tgt_idx = CAM_TYPE_PAIRS[args.cam_type]
    # One transition, reused for every subsequent view.
    cam_indices = [cond_idx, tgt_idx]

camera_embeddings_list, c2w_matrices = build_camera_chain(
    args.camera_json_path, cam_indices)

# ── Device ────────────────────────────────────────────────────────────────

if "LOCAL_RANK" in os.environ:
    dist.init_process_group(backend="nccl")
    local_rank = int(os.environ["LOCAL_RANK"])
    torch.cuda.set_device(local_rank)
    device = torch.device(f"cuda:{local_rank}")
    set_seed(args.seed + local_rank)
else:
    device = torch.device("cuda")
    local_rank = 0
    set_seed(args.seed)

print(f"Free VRAM {get_cuda_free_memory_gb(gpu)} GB")
low_memory = get_cuda_free_memory_gb(gpu) < 40

torch.set_grad_enabled(False)

# ── Config ────────────────────────────────────────────────────────────────

config = OmegaConf.load(args.config_path)
default_config = OmegaConf.load("configs/base.yaml")
config = OmegaConf.merge(default_config, config)
config.local_attn_size = args.local_attn_size
config.sink_size = args.sink_size

# ── Pipeline ──────────────────────────────────────────────────────────────

pipeline = TextToMVPipeline(config, device=device)

sf_sd = torch.load(args.sf_checkpoint_path, map_location="cpu")
key = "generator_ema" if "generator_ema" in sf_sd else "generator"
pipeline.sf_generator.load_state_dict(sf_sd[key] if key in sf_sd else sf_sd)
print(f"Self-Forcing weights loaded (key='{key}').")

student_sd = torch.load(args.checkpoint_path, map_location="cpu")
pipeline.student.load_state_dict(student_sd.get("generator", student_sd))
print("Student weights loaded.")

pipeline = pipeline.to(dtype=torch.bfloat16)
pipeline.cut3r_model = load_cut3r(args.cut3r_path, device, root=args.cut3r_root)
print("CUT3R model loaded.")

if low_memory:
    DynamicSwapInstaller.install_model(pipeline.text_encoder, device=gpu)
else:
    pipeline.text_encoder.to(device=gpu)
pipeline.sf_generator.to(device=gpu)
pipeline.student.to(device=gpu)
pipeline.vae.to(device=gpu)

# ── Generate ──────────────────────────────────────────────────────────────

if local_rank == 0:
    os.makedirs(args.output_folder, exist_ok=True)
if dist.is_initialized():
    dist.barrier()

# Cameras are static in time: expand the first frame to the requested length.
camera_embeddings_list = [
    emb[:, :1, :].expand(-1, args.total_frames, -1).to(device)
    for emb in camera_embeddings_list
]
c2w_matrices = [
    (cond[:1].expand(args.total_frames, -1, -1).to(device),
     tgt[:1].expand(args.total_frames, -1, -1).to(device))
    for cond, tgt in c2w_matrices
]

# A single transition is reused for every view step; an explicit chain
# provides one transition per step already.
if len(camera_embeddings_list) == 1 and args.num_views > 2:
    camera_embeddings_list = camera_embeddings_list * (args.num_views - 1)
    c2w_matrices = c2w_matrices * (args.num_views - 1)

cam_meta = {
    "cam_type": args.cam_type if args.cam_indices is None else "custom",
    "cam_indices": cam_indices,
    "num_views": args.num_views,
    "v0_mode": args.v0_mode,
    "total_frames": args.total_frames,
}

for idx, prompt in enumerate(tqdm(prompts, disable=(local_rank != 0))):
    if args.long_rolling:
        video = pipeline.inference_rolling_chain(
            text_prompts=[prompt] * 2,
            camera_embeddings_list=camera_embeddings_list,
            c2w_matrices=c2w_matrices,
            num_views=args.num_views,
            total_frames=args.total_frames,
            v0_mode=args.v0_mode,
            accumulate_views=args.accumulate_views,
        )
    elif args.total_frames > 21 or args.num_views > 2:
        video = pipeline.inference_long(
            text_prompts=[prompt, prompt],
            camera_embeddings=camera_embeddings_list[0],
            c2w_matrices=c2w_matrices,
            num_views=args.num_views,
            total_frames=args.total_frames,
            v0_mode=args.v0_mode,
            accumulate_views=args.accumulate_views,
        )
    else:
        cond_c2w, tgt_c2w = c2w_matrices[0]
        video = pipeline.inference(
            text_prompts=[prompt, prompt],
            camera_embeddings=camera_embeddings_list[0],
            c2w_cond=cond_c2w,
            c2w_tgt=tgt_c2w,
            negative_prompt=args.negative_prompt,
            v0_mode=args.v0_mode,
            num_frames=args.total_frames,
        )

    save_views(video, args.num_views, args.output_folder, args.method_name, idx,
               prompt_text=prompt, camera_config=cam_meta, fps=args.fps)
    pipeline.vae.model.clear_cache()
    if local_rank == 0:
        print(f"Saved: {args.method_name}/prompt_{idx:04d}")
